function readStored(): LabState {
  try {
    const raw = JSON.parse(localStorage.getItem(STORAGE_KEY) || "null") as Partial<LabState> | null;
    if (!raw || typeof raw !== "object") return DEFAULTS;
    const next: LabState = {
      ...DEFAULTS,
      ...raw,
      clinician: { ...DEFAULTS.clinician, ...(raw.clinician ?? {}) },
      files: Array.isArray(raw.files) ? raw.files.filter((file) => file && typeof file.name === "string") : [],
      report: raw.report && typeof raw.report === "object" ? raw.report : {},
    };
    next.nav = "workspace";
    if (next.surface !== "home" && next.surface !== "workspace") next.surface = "home";
    if (next.scribe === "running") next.scribe = "paused";
    return next;
  } catch {
    return DEFAULTS;
  }
}

function clock(seconds: number): string {
  return `${String(Math.floor(seconds / 60)).padStart(2, "0")}:${String(seconds % 60).padStart(2, "0")}`;
}

function initials(name: string): string {
  const parts = name.trim().split(/\s+/).filter(Boolean);
  if (!parts.length) return "VM";
  return parts
    .slice(0, 2)
    .map((part) => part[0]?.toUpperCase() ?? "")
    .join("");
}

function firstName(name: string): string {
  return name.trim().split(/\s+/)[0] || "there";
}

function hasDraft(report: ReportDoc): boolean {
  return Object.keys(report).length > 0;
}

function PlainText({
  value,
  label,
  placeholder,
  onChange,
}: {
  value: string;
  label: string;
  placeholder?: string;
  onChange: (text: string) => void;
}) {
  const ref = useRef<HTMLDivElement>(null);
  useLayoutEffect(() => {
    const node = ref.current;
    if (!node || document.activeElement === node) return;
    if ((node.innerText || "").replace(/\n$/, "") !== value) node.innerText = value;
  }, [value]);
  return (
    <div
      ref={ref}
      contentEditable
      role="textbox"
      aria-multiline="true"
      aria-label={label}
      data-placeholder={placeholder}
      spellCheck
      suppressContentEditableWarning
      onInput={() => onChange((ref.current?.innerText || "").replace(/\n$/, ""))}
    />
  );
}

